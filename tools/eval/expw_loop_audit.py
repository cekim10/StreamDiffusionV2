#!/usr/bin/env python3
"""Experiment W: loop-boundary audit of the harness's input feeding (arithmetic only; no video is read, no GPU).

The harness (tools/proto_handoff.build_runtime -> tools/state_ablation.Runner) feeds call c the input frames
[first + chunk * c, first + chunk * c + chunk) of the clip repeated end-to-end (`video.repeat`, hard cut), with
first = 1 + chunk = 5 (the session's first batch, frames 0..4) and chunk = 4. A call is a **cut call** when its input
chunk contains a repeated-tensor frame index f > 0 with f mod T == 0 (the first frame of a new pass). Output at call c is
the decode of input chunk c - (k - 1) (Stream-Batch lag, k = 2), so a cut reaches the output one call later.
Boundary-adjacent calls = a cut call and the 2 calls after it (window fixed in expT/sink_stability_plan.md, 2026-10-17).

    python3 tools/eval/expw_loop_audit.py            # writes results/evaluation/osdi/expW/loop_audit.{json,md}
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "results/evaluation/osdi/expW"
CHUNK, FIRST, ADJ = 4, 5, 2
W1_CALLS, W1_FROM = 330, 30                 # W1: calls 0..329, statistics over 30..329
WINDOWS = (6, 25, 52)                        # P_w windows (sink_stability_plan.md)
HORIZON, BIND_EST = 100, 26                  # W2: trigger + 100 calls; ~26 calls to bind at 1 Gbps (T_ref 14.05 s / 0.556 s + bind)
TRIGGERS = (30, 34)                          # ExpD's M and the candidate alternative
REPO = {"dog (original.mp4)": 81, "bird": 254, "boxing": 251, "train": 65}   # frame counts measured 2026-10-18


def cut_calls(T: int, n_calls: int) -> list[int]:
    return [c for c in range(n_calls) if any(f > 0 and f % T == 0 for f in range(FIRST + CHUNK * c, FIRST + CHUNK * c + CHUNK))]


def first_pass_calls(T: int, n_calls: int) -> int:
    return sum(1 for c in range(n_calls) if FIRST + CHUNK * c + CHUNK - 1 < T)


def audit(name: str, T: int, group: str) -> dict:
    cuts = cut_calls(T, W1_CALLS + 10)
    adj = {c + d for c in cuts for d in range(ADJ + 1)}
    calls = range(W1_FROM, W1_CALLS)
    within = [c for c in calls if c not in adj]
    feas = {}
    for w in WINDOWS:
        starts = [c for c in range(W1_FROM, W1_CALLS - w) if not any(x in adj for x in range(c, c + w + 1))]
        feas[w] = {"windows": W1_CALLS - w - W1_FROM, "within_clip_windows": len(starts)}
    w2 = {}
    for M in TRIGGERS:
        w2[M] = {"trigger_is_cut_call": M in cuts, "trigger_boundary_adjacent": M in adj,
                 "cuts_in_restoration_window": [c for c in cuts if M <= c < M + BIND_EST],
                 "cuts_in_horizon": len([c for c in cuts if M <= c < M + HORIZON]),
                 "nearest_cut_before_trigger": max([c for c in cuts if c <= M], default=None)}
    return {"workload": name, "group": group, "T_frames": T, "loop_period_calls": T / CHUNK,
            "first_pass_calls": first_pass_calls(T, W1_CALLS), "cut_calls_0_329": [c for c in cuts if c < W1_CALLS],
            "W1_calls_30_329": len(calls), "W1_boundary_adjacent": len(calls) - len(within), "W1_within_clip": len(within),
            "W1_window_feasibility": feas, "W2": w2}


def main():
    rows = [audit(n, T, "repo") for n, T in REPO.items()]
    with open(OUT / "loveu_selection.csv", newline="") as fh:
        for r in csv.DictReader(fh):
            rows.append(audit(r["video_id"], int(r["frames"]), f"LOVEU {r['frames']}-frame"))
    (OUT / "loop_audit.json").write_text(json.dumps(rows, indent=1))
    L = ["# Experiment W loop-boundary audit (generated by tools/eval/expw_loop_audit.py; arithmetic only)", "",
         f"chunk {CHUNK} frames, first batch {FIRST} frames, boundary-adjacent = cut call + {ADJ}; W1 statistics over calls "
         f"{W1_FROM}-{W1_CALLS - 1}; W2 restoration window = trigger .. trigger + {BIND_EST - 1}, horizon trigger + {HORIZON}.", "",
         "| workload | T | period (calls) | first-pass calls | cut calls (first 6) | W1 within-clip / adjacent | within-clip windows w=6 / 25 / 52 | M=30: trigger cut? / cuts before bind / cuts in horizon | M=34: same |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        f = r["W1_window_feasibility"]
        m30, m34 = r["W2"][30], r["W2"][34]
        L.append(f"| {r['workload']} | {r['T_frames']} | {r['loop_period_calls']:g} | {r['first_pass_calls']} | {r['cut_calls_0_329'][:6]} | "
                 f"{r['W1_within_clip']} / {r['W1_boundary_adjacent']} | {f[6]['within_clip_windows']} / {f[25]['within_clip_windows']} / {f[52]['within_clip_windows']} | "
                 f"{'**yes**' if m30['trigger_is_cut_call'] else 'no'} / {len(m30['cuts_in_restoration_window'])} / {m30['cuts_in_horizon']} | "
                 f"{'**yes**' if m34['trigger_is_cut_call'] else ('adjacent' if m34['trigger_boundary_adjacent'] else 'no')} / {len(m34['cuts_in_restoration_window'])} / {m34['cuts_in_horizon']} |")
    (OUT / "loop_audit.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
